import chromium, { inflate, setupLambdaEnvironment } from '@sparticuz/chromium';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
const bin = join(dirname(fileURLToPath(import.meta.resolve('@sparticuz/chromium'))), '..', 'bin');
await inflate(join(bin, 'al2023.tar.br'));
await inflate(join(bin, 'fonts.tar.br'));
setupLambdaEnvironment(join(tmpdir(), 'al2023', 'lib'));
const puppeteer = (await import('puppeteer-core')).default;
const browser = await puppeteer.launch({ headless: true, executablePath: await chromium.executablePath(), args: chromium.args });
const errors=[];
const page = await browser.newPage();
page.on('pageerror', e => errors.push(String(e)));
await page.setViewport({ width: 1280, height: 720 });
await page.goto('http://localhost:3000', { waitUntil: 'load', timeout: 30000 });
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: 'load' });
await page.evaluate(() => document.fonts.ready);
console.log('customize-btn:', await page.$eval('#customize-btn', e => e.textContent));
console.log('quests-btn html:', (await page.$eval('#quests-btn', e => e.outerHTML)).slice(0, 200));
await page.click('#quests-btn');
await new Promise(r => setTimeout(r, 800));
console.log('dialog count:', await page.evaluate(() => document.querySelectorAll('.quest-board-dialog').length));
console.log('dialog open:', await page.evaluate(() => document.querySelector('.quest-board-dialog')?.open));
console.log('errors:', JSON.stringify(errors));
await browser.close();
